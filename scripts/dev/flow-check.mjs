import puppeteer from 'puppeteer-core'
const base = process.argv[2] ?? 'http://localhost:5173'
const out = '../cook/stills/r07'
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const page = await browser.newPage()
await page.setViewport({ width: 1440, height: 900 })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && !/api\/intent/.test(m.text()) && errors.push(m.text()))
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const clickText = (t) => page.evaluate((t) => { const b = [...document.querySelectorAll('button')].find((x) => x.textContent.trim() === t); b?.click(); return !!b }, t)
await page.goto(base + '/?nolive', { waitUntil: 'networkidle0' })
await wait(7000)
await page.screenshot({ path: `${out}/S01-dense.png` })
// 1. vague request -> dialog
await page.type('.search input', 'Something fun to do')
await page.keyboard.press('Enter')
await page.waitForSelector('.clarify', { timeout: 15000 })
await wait(600)
await page.screenshot({ path: `${out}/F1-dialog.png` })
const qs = await page.evaluate(() => [...document.querySelectorAll('.cq-label')].map((x) => x.textContent))
console.log('questions:', qs)
for (const t of ['Singapore', 'Things to do', 'Family, 2 adults 2 kids', 'This weekend', 'Hotel transfer', 'Little walking']) console.log('click', t, await clickText(t))
await clickText('Show my results')
await wait(1500)
await page.screenshot({ path: `${out}/F2-personal.png` })
console.log('after: hash', await page.evaluate(() => location.hash), 'chips', await page.evaluate(() => [...document.querySelectorAll('.p-request .personal .chip')].map((x) => x.textContent)))
console.log('top offer:', await page.evaluate(() => document.querySelector('.p-ranked .tbl-name')?.textContent))
// 2. a destination outside the demo graph goes to the live supplier page
await page.focus('.search input')
await page.keyboard.down('Control'); await page.keyboard.press('KeyA'); await page.keyboard.up('Control'); await page.keyboard.press('Backspace')
await page.type('.search input', 'Hotel in Dubai for a couple next weekend')
await page.keyboard.press('Enter')
await page.waitForFunction(() => location.hash.includes('live'), { timeout: 20000 })
await page.waitForSelector('.lcard:not(.skeleton), .live-empty', { timeout: 30000 })
await wait(1500)
await page.screenshot({ path: `${out}/F3-live-dubai.png` })
console.log('after: hash', await page.evaluate(() => location.hash), '| title', await page.evaluate(() => document.querySelector('.live-title')?.textContent), '| banner', await page.evaluate(() => document.querySelector('.live-banner')?.textContent?.slice(0, 60)), '| cards', await page.evaluate(() => document.querySelectorAll('.lcard').length))
console.log(errors.length ? 'errors: ' + errors.join(' | ') : 'no page errors')
await browser.close()
